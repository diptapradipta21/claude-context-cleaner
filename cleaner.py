#!/usr/bin/env python3
"""
claude-context-cleaner — Zero-Token Context & Waste Pruner for Claude Code and Autonomous AI Agents.
Scans workspace directories, identifies token-bloating artifacts (lockfiles, oversized logs, build caches, minified assets),
generates clean .claudeignore rules, and prunes disposable caches to conserve Claude's context window.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any, Dict, List, Tuple

# Standard directories that waste AI context tokens
BLOAT_DIRECTORIES = {
    "node_modules", ".git", ".cache", "__pycache__", ".venv", "venv", "dist", "build",
    ".next", ".nuxt", "coverage", ".turbo", ".gradle", "target", ".idea", ".vscode"
}

# Standard file extensions that waste AI context tokens
BLOAT_EXTENSIONS = {
    ".lock", ".log", ".map", ".min.js", ".min.css", ".pyc", ".pyo", ".pyd",
    ".bin", ".exe", ".dll", ".so", ".dylib", ".iso", ".tar", ".gz", ".zip", ".7z",
    ".parquet", ".sqlite", ".db", ".sqlite3", ".pkl", ".h5", ".onnx", ".mp4", ".mp3", ".wav"
}

# Specific lockfiles and token sinks that might have regular extensions like .json or .yaml
BLOAT_FILENAMES = {
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "poetry.lock",
    "pipfile.lock", "cargo.lock", "composer.lock", "gemfile.lock"
}

# Disposable ephemeral artifacts safe to prune
SAFE_PRUNE_EXTENSIONS = {".pyc", ".pyo", ".DS_Store"}
SAFE_PRUNE_NAMES = {".coverage"}

DEFAULT_CLAUDEIGNORE = """# Generated by claude-context-cleaner
# Optimize context window & reduce wasted tokens

# Package managers & build artifacts
node_modules/
dist/
build/
.next/
.turbo/
target/
__pycache__/
*.pyc
.venv/
venv/

# Lock files & maps (heavy token sinks)
package-lock.json
yarn.lock
pnpm-lock.yaml
poetry.lock
Pipfile.lock
*.map
*.min.js
*.min.css

# Binary, media & heavy databases
*.sqlite
*.sqlite3
*.db
*.parquet
*.onnx
*.pkl
*.bin
*.tar
*.gz
*.zip
*.mp4
*.mp3
*.wav

# Coverage & test output
coverage/
*.lcov
"""


def estimate_tokens(file_size_bytes: int) -> int:
    """Rough heuristic: ~1 token per 3.8-4 bytes of plain code/json text."""
    return int(file_size_bytes / 3.9)


def scan_directory(
    root_dir: str,
    size_threshold_kb: int = 100,
    top_n: int = 15,
    as_json: bool = False,
    summary_only: bool = False
) -> Tuple[List[Dict[str, Any]], int, int]:
    root = Path(root_dir).resolve()
    if not root.exists():
        if as_json:
            print(json.dumps({"error": f"Path does not exist: {root}"}))
        else:
            print(f"[x] Error: Path does not exist: {root}", file=sys.stderr)
        return [], 0, 0

    if not as_json and not summary_only:
        print(f"[*] Scanning workspace for token bloat: {root}")

    bloat_files: List[Dict[str, Any]] = []
    total_wasted_bytes = 0

    for dirpath, dirnames, filenames in os.walk(root):
        rel_dir = os.path.relpath(dirpath, root)
        parts = rel_dir.split(os.sep) if rel_dir != "." else []
        is_bloat_dir = any(p in BLOAT_DIRECTORIES for p in parts)

        for f in filenames:
            file_path = Path(dirpath) / f
            try:
                stat = file_path.stat()
                size = stat.st_size
                ext = file_path.suffix.lower()

                is_large = size > (size_threshold_kb * 1024)
                is_bloat_ext = ext in BLOAT_EXTENSIONS
                is_bloat_name = f.lower() in BLOAT_FILENAMES

                if is_bloat_dir or is_bloat_ext or is_bloat_name or is_large:
                    tokens = estimate_tokens(size)
                    total_wasted_bytes += size
                    bloat_files.append({
                        "path": str(file_path.relative_to(root)),
                        "size_bytes": size,
                        "size_kb": round(size / 1024, 2),
                        "estimated_tokens": tokens,
                        "is_bloat_dir": is_bloat_dir,
                        "is_bloat_ext": is_bloat_ext,
                        "is_bloat_name": is_bloat_name,
                        "is_oversized": is_large
                    })
            except (OSError, PermissionError):
                continue

    bloat_files.sort(key=lambda x: x["size_bytes"], reverse=True)
    total_tokens = estimate_tokens(total_wasted_bytes)

    if as_json:
        payload = {
            "root": str(root),
            "file_count": len(bloat_files),
            "total_wasted_bytes": total_wasted_bytes,
            "total_wasted_mb": round(total_wasted_bytes / (1024 * 1024), 2),
            "estimated_wasted_tokens": total_tokens,
            "files": bloat_files[:top_n] if top_n > 0 else bloat_files
        }
        print(json.dumps(payload, indent=2))
        return bloat_files, total_tokens, total_wasted_bytes

    total_mb = total_wasted_bytes / (1024 * 1024)
    print(f"[!] Found {len(bloat_files)} potential context-bloating files.")
    print(f"[!] Total potential waste: {total_mb:.2f} MB (~{total_tokens:,} tokens)\n")

    if not summary_only and bloat_files:
        limit = top_n if top_n > 0 else len(bloat_files)
        print(f"{'Path':<65} | {'Size':<10} | {'Est. Tokens'}")
        print("-" * 95)
        for item in bloat_files[:limit]:
            size = item["size_bytes"]
            size_str = f"{size / 1024:.1f} KB" if size < 1024 * 1024 else f"{size / (1024 * 1024):.2f} MB"
            print(f"{item['path'][:63]:<65} | {size_str:<10} | ~{item['estimated_tokens']:,}")

    return bloat_files, total_tokens, total_wasted_bytes


def prune_cache(
    root_dir: str,
    dry_run: bool = False,
    as_json: bool = False
) -> Tuple[int, int, List[str]]:
    """Safely removes ephemeral cache files (.pyc, .pyo, .DS_Store, .coverage, empty __pycache__)."""
    root = Path(root_dir).resolve()
    if not root.exists():
        return 0, 0, []

    pruned_paths: List[str] = []
    freed_bytes = 0
    pycache_dirs: List[Path] = []

    for dirpath, dirnames, filenames in os.walk(root):
        if ".git" in dirnames:
            dirnames.remove(".git")
        if os.path.basename(dirpath) == "__pycache__":
            pycache_dirs.append(Path(dirpath))

        for f in filenames:
            fp = Path(dirpath) / f
            ext = fp.suffix.lower()
            if ext in SAFE_PRUNE_EXTENSIONS or f in SAFE_PRUNE_NAMES:
                try:
                    size = fp.stat().st_size
                    freed_bytes += size
                    pruned_paths.append(str(fp.relative_to(root)))
                    if not dry_run:
                        fp.unlink(missing_ok=True)
                except (OSError, PermissionError):
                    continue

    # Cleanup empty __pycache__ directories
    if not dry_run:
        for pdir in pycache_dirs:
            try:
                if pdir.exists() and not any(pdir.iterdir()):
                    pdir.rmdir()
            except (OSError, PermissionError):
                pass

    if as_json:
        payload = {
            "action": "prune_cache",
            "dry_run": dry_run,
            "pruned_count": len(pruned_paths),
            "freed_bytes": freed_bytes,
            "freed_kb": round(freed_bytes / 1024, 2),
            "pruned_files": pruned_paths
        }
        print(json.dumps(payload, indent=2))
    else:
        prefix = "[DRY-RUN] Would prune" if dry_run else "[✓] Pruned"
        freed_kb = freed_bytes / 1024
        print(f"\n{prefix} {len(pruned_paths)} cache files ({freed_kb:.1f} KB freed).")

    return len(pruned_paths), freed_bytes, pruned_paths


def generate_claudeignore(
    root_dir: str,
    force: bool = False,
    append: bool = False,
    as_json: bool = False
) -> bool:
    target = Path(root_dir) / ".claudeignore"
    if target.exists() and not force and not append:
        msg = f".claudeignore already exists at {target}. Use --force to overwrite or --append-ignore to add."
        if as_json:
            print(json.dumps({"status": "skipped", "message": msg}))
        else:
            print(f"\n[!] {msg}")
        return False

    mode = "a" if (target.exists() and append) else "w"
    content = f"\n\n{DEFAULT_CLAUDEIGNORE}" if mode == "a" else DEFAULT_CLAUDEIGNORE

    with open(target, mode, encoding="utf-8") as f:
        f.write(content)

    action_label = "appended to" if mode == "a" else "created"
    if as_json:
        print(json.dumps({"status": action_label, "path": str(target)}))
    else:
        print(f"\n[✓] Successfully {action_label} optimized .claudeignore at: {target}")
    return True


def main() -> None:
    parser = argparse.ArgumentParser(description="Audit and clean token waste for Claude Code and AI coding agents.")
    parser.add_argument("path", nargs="?", default=".", help="Workspace path to scan (default: current directory)")
    parser.add_argument("--init-ignore", action="store_true", help="Generate optimized .claudeignore in target path")
    parser.add_argument("--append-ignore", action="store_true", help="Append rules to existing .claudeignore without overwrite")
    parser.add_argument("--threshold", type=int, default=100, help="File size threshold in KB to flag (default: 100)")
    parser.add_argument("--top", type=int, default=15, help="Number of largest bloat files to display (default: 15)")
    parser.add_argument("--summary-only", action="store_true", help="Display aggregate waste metrics without itemized table")
    parser.add_argument("--json", action="store_true", help="Output audit results as machine-readable JSON")
    parser.add_argument("--force", action="store_true", help="Overwrite existing .claudeignore")
    parser.add_argument("--prune-cache", action="store_true", help="Safely remove ephemeral caches (.pyc, .DS_Store, empty __pycache__)")
    parser.add_argument("--dry-run", action="store_true", help="Simulate prune operation without deleting files")
    parser.add_argument("--fail-on-waste-mb", type=float, default=None, help="Exit code 2 if total wasted MB exceeds this limit")

    args = parser.parse_args()

    _, total_tokens, total_bytes = scan_directory(
        args.path,
        size_threshold_kb=args.threshold,
        top_n=args.top,
        as_json=args.json,
        summary_only=args.summary_only
    )

    if args.prune_cache:
        prune_cache(args.path, dry_run=args.dry_run, as_json=args.json)

    if args.init_ignore or args.append_ignore:
        generate_claudeignore(args.path, force=args.force, append=args.append_ignore, as_json=args.json)

    if args.fail_on_waste_mb is not None:
        wasted_mb = total_bytes / (1024 * 1024)
        if wasted_mb > args.fail_on_waste_mb:
            if not args.json:
                print(f"\n[x] Failure: Total waste ({wasted_mb:.2f} MB) exceeds threshold ({args.fail_on_waste_mb:.2f} MB).", file=sys.stderr)
            sys.exit(2)


if __name__ == "__main__":
    main()
